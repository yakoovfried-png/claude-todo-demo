#!/usr/bin/env python3
"""Convert prompts.chat's prompts.csv (CC0) into data/prompts.js for the static library.

Usage: python3 scripts/build_data.py path/to/prompts.csv
"""
import csv
import json
import sys

csv.field_size_limit(10**9)

src = sys.argv[1] if len(sys.argv) > 1 else "prompts.csv"
out = "data/prompts.js"

prompts = []
with open(src, encoding="utf-8") as f:
    for row in csv.DictReader(f):
        title = (row.get("act") or "").strip()
        text = (row.get("prompt") or "").strip()
        if not title or not text:
            continue
        prompts.append({
            "t": title,
            "p": text,
            "d": row.get("for_devs", "").upper() == "TRUE",
            "k": (row.get("type") or "TEXT").upper(),
        })

with open(out, "w", encoding="utf-8") as f:
    f.write("// Generated by scripts/build_data.py from prompts.chat (CC0 1.0). Do not edit.\n")
    f.write("window.PROMPTS = ")
    json.dump(prompts, f, ensure_ascii=False, separators=(",", ":"))
    f.write(";\n")

print(f"{len(prompts)} prompts -> {out}")
